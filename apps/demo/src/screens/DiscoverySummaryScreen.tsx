import { useId, useState } from 'react';
import { ArrowClockwiseIcon, CheckIcon, DownloadSimpleIcon } from '@phosphor-icons/react';
import {
  AgentBlock,
  AttachmentRow,
  Button,
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from 'tabular-ui';

import { evidenceSheetCount, formatMinutes, type JourneyFile } from '../lib/files';
import { findingsIn, foundIn } from '../lib/findings';
import { discoveryBullets, kasanePack } from '../lib/kasane';
import type { RunOutcome } from './ReadingScreen';
import type { RecapCounts } from './RecapScreen';

export type DiscoverySummaryScreenProps = {
  files: JourneyFile[];
  outcome: RunOutcome;
  counts: RecapCounts;
  /** Re-runs the analysis over the same material. */
  onRestartAnalysis: () => void;
};

/** The label over every agent-authored part of this screen, and the actor on its export. */
const AUTHORSHIP = 'Generated by AI';

/**
 * The first component of the modeling surface: what the run understood, and
 * what it found, before the user goes further.
 *
 * Agent-authored, so it is an `AgentBlock` with its label (CLAUDE.md; agent
 * voice, Decided rule 1). Until 2026-10-21 it was neutral, by an owner
 * exception from 2026-08-24, and the contradictions, gaps and questions were
 * only in the download. The owner reversed both on 2026-10-21.
 *
 * Everything shown is scripted, not derived from the run: `lib/kasane.ts`,
 * generated from the Kasane dataset, so every figure is true of the files the
 * demo loads. Each bullet and finding names the files it rests on, and shows
 * only once every one of them was read.
 */
export function DiscoverySummaryScreen({ files, outcome, counts, onRestartAnalysis }: DiscoverySummaryScreenProps) {
  const [documentsOpen, setDocumentsOpen] = useState(false);

  const read = files.slice(0, outcome.filesRead);
  const bullets = foundIn(discoveryBullets, read);
  const found = findingsIn(read);
  const anything = bullets.length + found.contradictions.length + found.gaps.length + found.followUps.length > 0;
  const partial = outcome.filesRead < outcome.totalFiles;

  // The script knows Kasane's material only. With other files the flow runs,
  // and this says so rather than summarising files it never read.
  const packNames = new Set(kasanePack.map((f) => f.name));
  const kasaneLoaded = files.some((f) => packNames.has(f.name));
  const nothingFound = kasaneLoaded
    ? 'The run stopped before it read enough of Kasane’s files to summarise them. Restart the analysis to read the rest.'
    : 'This demo’s agent is scripted for Kasane Corporation’s files, so it has nothing to summarise from these. Load Kasane’s files to see a full summary.';
  const scope = `I read ${outcome.filesRead} of ${outcome.totalFiles} files. Anything that rests on the others is left out.`;

  const download = () => {
    const sourced = (sources: readonly string[]) => ` (${sources.join(', ')})`;
    const lines = [
      '# Business discovery summary',
      '',
      ...(anything
        ? [
            `${AUTHORSHIP}. Not yet reviewed.`,
            '',
            ...(partial ? [scope, ''] : []),
            ...(bullets.length
              ? ['## Understood from your material', ...bullets.map((b) => `- ${b.text}${sourced(b.sources)}`), '']
              : []),
            ...(found.contradictions.length
              ? [
                  '## Contradictions between sources',
                  ...found.contradictions.map((c) => `- ${c.claim} ${c.evidence}${sourced(c.sources)}`),
                  '',
                ]
              : []),
            ...(found.gaps.length
              ? ['## Gaps in the material', ...found.gaps.map((g) => `- ${g.text}${sourced(g.sources)}`), '']
              : []),
            ...(found.followUps.length
              ? ['## Questions to ask', ...found.followUps.map((q) => `- ${q.text}${sourced(q.sources)}`), '']
              : []),
          ]
        : [nothingFound, '']),
      '## Run',
      `- Files read: ${outcome.filesRead} of ${outcome.totalFiles}`,
      `- Evidence sheets: ${evidenceSheetCount(counts)}`,
      `- Elapsed: ${formatMinutes(outcome.elapsedMinutes)}`,
      '',
      '## Documents',
      ...read.map((f) => `- ${f.name}`),
      '',
    ];
    const url = URL.createObjectURL(new Blob([lines.join('\n')], { type: 'text/markdown' }));
    const a = document.createElement('a');
    a.href = url;
    a.download = 'business-discovery-summary.md';
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <section className="flex flex-col rounded-md border border-border bg-surface">
      {/* §7.4 fallback: no role token for a panel header's vertical padding —
          py-2 (8px) named explicitly, matching AppBar's own fallback. */}
      <header className="flex items-center border-b border-border px-[var(--pad-card)] py-2">
        <h1 className="text-md font-medium text-text-primary">Business discovery summary</h1>
      </header>

      <div className="p-[var(--pad-card)]">
        {anything ? (
          <AgentBlock authorship={AUTHORSHIP}>
            <div className="flex flex-col gap-[var(--gap-section)]">
              {partial ? <p className="text-sm text-text-body">{scope}</p> : null}

              {bullets.length ? (
                <FindingList label="Understood from your material">
                  {bullets.map((b) => (
                    <li key={b.id} className="flex items-start gap-[var(--gap-control-icon)]">
                      {/* A list marker, not a state — neutral (§0 rule 1). */}
                      <CheckIcon
                        weight="bold"
                        aria-hidden="true"
                        className="mt-px size-[var(--size-icon-sm)] shrink-0 text-text-secondary"
                      />
                      <Finding sources={b.sources}>{b.text}</Finding>
                    </li>
                  ))}
                </FindingList>
              ) : null}

              {found.contradictions.length ? (
                <FindingList label="Contradictions between sources" count={found.contradictions.length}>
                  {found.contradictions.map((c) => (
                    <li key={c.id}>
                      <Finding sources={c.sources}>
                        {/* What was said, then what the files show. */}
                        <span className="block text-text-primary">{c.claim}</span>
                        {c.evidence}
                      </Finding>
                    </li>
                  ))}
                </FindingList>
              ) : null}

              {found.gaps.length ? (
                <FindingList label="Gaps in the material" count={found.gaps.length}>
                  {found.gaps.map((g) => (
                    <li key={g.id}>
                      <Finding sources={g.sources}>{g.text}</Finding>
                    </li>
                  ))}
                </FindingList>
              ) : null}

              {found.followUps.length ? (
                <FindingList label="Questions to ask" count={found.followUps.length}>
                  {found.followUps.map((q) => (
                    <li key={q.id}>
                      <Finding sources={q.sources}>{q.text}</Finding>
                    </li>
                  ))}
                </FindingList>
              ) : null}
            </div>
          </AgentBlock>
        ) : (
          <p className="text-sm text-text-body">{nothingFound}</p>
        )}
      </div>

      <footer className="flex items-center gap-[var(--gap-inline)] border-t border-border px-[var(--pad-card)] py-2">
        <Button variant="ghost" onClick={() => setDocumentsOpen(true)}>
          View documents
        </Button>
        <span className="flex-1" />
        <Button variant="outline" onClick={onRestartAnalysis}>
          <ArrowClockwiseIcon weight="bold" aria-hidden="true" />
          Restart analysis
        </Button>
        <Button onClick={download}>
          <DownloadSimpleIcon weight="bold" aria-hidden="true" />
          Download summary
        </Button>
      </footer>

      <Dialog open={documentsOpen} onOpenChange={setDocumentsOpen}>
        <DialogContent className="sm:max-w-md">
          <DialogHeader>
            <DialogTitle>Documents</DialogTitle>
            <DialogDescription>
              The {read.length === 1 ? 'file' : `${read.length} files`} this summary was drawn from.
            </DialogDescription>
          </DialogHeader>
          {/* py-1 keeps focus rings clear of the scroll edges (§4). */}
          <ul role="list" className="max-h-[336px] overflow-y-auto py-1">
            {read.map((f) => (
              <li key={f.id}>
                <AttachmentRow name={f.name} status={f.status} />
              </li>
            ))}
          </ul>
        </DialogContent>
      </Dialog>
    </section>
  );
}

/** One group of findings: a micro-label, then its list, named by the label. */
function FindingList({ label, count, children }: { label: string; count?: number; children: React.ReactNode }) {
  const id = useId();
  return (
    <div className="flex flex-col gap-[var(--gap-field)]">
      <span id={id} className="text-2xs font-medium uppercase tracking-[var(--tracking-wide)] text-text-secondary">
        {label}
        {count ? ` · ${count}` : null}
      </span>
      {/* role="list" is explicit: Tailwind preflight strips list-style and
          Safari then drops list semantics (see AppBar). */}
      <ul role="list" aria-labelledby={id} className="flex flex-col gap-[var(--gap-group)]">
        {children}
      </ul>
    </div>
  );
}

/**
 * A finding and the files it rests on, so every claim can be checked (agent
 * voice, Principle 2). File names are identifiers: mono, one step below the
 * sentence (§8.3).
 */
function Finding({ sources, children }: { sources: readonly string[]; children: React.ReactNode }) {
  return (
    <div className="flex min-w-0 flex-col gap-[var(--gap-bonded)]">
      <p className="text-sm text-text-body">{children}</p>
      <p className="font-mono text-xs break-words text-text-secondary">
        <span className="sr-only">From </span>
        {sources.join(' · ')}
      </p>
    </div>
  );
}
