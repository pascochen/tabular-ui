import type { Meta, StoryObj } from '@storybook/react-vite';
import { expect } from 'storybook/test';

import { Button } from '../../foundational/Button';
import { CodeView } from '../CodeView';
import { AgentBlock } from './index';

const meta = {
  title: 'Product/AgentBlock',
  component: AgentBlock,
  parameters: { layout: 'padded' },
  args: { authorship: 'Generated by AI', children: 'Agent-authored content.' },
} satisfies Meta<typeof AgentBlock>;
export default meta;
type Story = StoryObj<typeof meta>;

export const Default: Story = {
  args: {
    authorship: 'Generated by AI',
    meta: '2 minutes ago',
    children:
      'dim_accounts failed its uniqueness test on account_id. 412 duplicate rows came from the SAP delta load overlapping the prior window. A dedupe step keyed on (account_id, valid_from) would remove them.',
  },
  play: async ({ canvasElement }) => {
    const block = canvasElement.querySelector<HTMLElement>('[data-slot="agent-block"]')!;
    const style = getComputedStyle(block);
    const token = (name: string) => {
      // Resolve a colour token the way the browser paints it.
      const probe = document.createElement('div');
      probe.style.color = `var(${name})`;
      block.append(probe);
      const value = getComputedStyle(probe).color;
      probe.remove();
      return value;
    };
    // §5, 2026-10-14: orchid (violet until 2026-10-16) is the rail and the label, nothing else. A
    // neutral box with no ground of its own, and no icon.
    await expect(style.backgroundColor).toBe('rgba(0, 0, 0, 0)');
    await expect(style.borderTopColor).toBe(token('--color-border'));
    // Solid, not the tint: the rail is a required signal and needs 3:1.
    await expect(style.borderLeftColor).toBe(token('--color-text-agent'));
    await expect(parseFloat(style.borderLeftWidth)).toBe(2);
    await expect(block.querySelector('svg')).toBeNull();
    const label = block.querySelector('.uppercase')!;
    await expect(getComputedStyle(label).color).toBe(token('--color-text-agent'));
  },
};

