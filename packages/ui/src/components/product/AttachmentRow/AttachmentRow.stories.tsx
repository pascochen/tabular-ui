/**
 * The upload affordance — a composition, not a component.
 *
 * `EmptyState` supplies the whole resting shape; the container adds a dashed
 * border and the input. **Dashed means a placeholder awaiting content, solid
 * means content** — so the border goes solid the moment a file lands, and an
 * `AttachmentRow` holding a real file is never dashed.
 */
export const UploadTarget: Story = {
  render: function UploadTargetStory() {
    const inputId = useId();
    const inputRef = useRef<HTMLInputElement>(null);
    const [file, setFile] = useState<string | null>(null);

    return (
      <div className="flex max-w-md flex-col gap-[var(--gap-field)]">
        <div className={file ? 'rounded-md border border-border' : 'rounded-md border border-dashed border-border'}>
          {file ? (
            <AttachmentRow
              name={file}
              size="2.4 MB"
              status="passed"
              actions={
                <IconButton aria-label="Remove" size="sm" onClick={() => setFile(null)}>
                  <TrashIcon />
                </IconButton>
              }
            />
          ) : (
            <EmptyState
              size="sm"
              icon={UploadSimpleIcon}
              title="No source file"
              description="CSV, XLSX or a SAP extract."
              action={
                <>
                  <Button onClick={() => inputRef.current?.click()}>Choose file</Button>
                  {/*
                    The native input does the work; the Button is the only control.
                    `aria-hidden` + `tabIndex={-1}` are load-bearing: Chrome exposes a
                    bare `input[type=file]` as its own button named "Choose File", so
                    without these a screen reader announces two identically-named
                    buttons and the tab order stops on an invisible one. Hiding it from
                    AT is safe precisely because it is out of the tab order.
                  */}
                  <input
                    ref={inputRef}
                    id={inputId}
                    type="file"
                    accept=".csv,.xlsx,.xls,.txt"
                    className="sr-only"
                    aria-hidden="true"
                    tabIndex={-1}
                    onChange={(e) => setFile(e.target.files?.[0]?.name ?? null)}
                  />
                </>
              }
            />
          )}
        </div>
        <p className="text-xs text-text-secondary">
          Click "Choose file" — the border goes solid once a file is attached.
        </p>
      </div>
    );
  },
};

